"""
Reduce a run directory of currents_3pt_*.h5 to one compact .npz.

Keeps only what the Lanczos extraction needs, the two-time objects, binned
over contiguous walker blocks (Metropolis neighbours are correlated):
    Ws2[iQ, i, j, b] = C2(t_i + t_j)        Gram matrix of the Krylov vectors
    C3N[iQ, i, j, b] = C_J(leg1=t_i, leg2=t_j)
A 2000-walker, 7-Q dataset is ~1 GB of h5 and ~20 MB here, so the h5 can be
deleted without losing the ability to re-extract.

Usage: python gfmc_reduce.py <run_dir> <out.npz> [n_bins=100]
"""
import sys, glob, re
import numpy as np, h5py

run_dir, out = sys.argv[1], sys.argv[2]
n_bins = int(sys.argv[3]) if len(sys.argv) > 3 else 100
Qs, W, C, tau = [], [], [], None
for f in sorted(x for x in glob.glob(f'{run_dir}/currents_3pt_*.h5') if 'korr' not in x):
    Q = float(re.search(r'Qmag([0-9.eE+-]+)\.h5', f).group(1))
    with h5py.File(f, 'r') as h:
        if 'C3_N_offdiag' not in h:
            sys.exit(f'{f}: no C3_N_offdiag -- generated by a pre-fix generator')
        w = np.real(np.array(h['Ws2_offdiag']))
        c = np.real(np.array(h['C3_N_offdiag']))
        if 'tau_values' in h: tau = np.array(h['tau_values'])
    nw = w.shape[-1] // n_bins * n_bins
    W.append(w[..., :nw].reshape(*w.shape[:2], n_bins, -1).mean(-1))
    C.append(c[..., :nw].reshape(*c.shape[:2], n_bins, -1).mean(-1))
    Qs.append(Q)
if not Qs:
    sys.exit(f'{run_dir}: no currents_3pt h5 found')
o = np.argsort(Qs)
np.savez_compressed(out, Q=np.array(Qs)[o], Ws2=np.array(W)[o], C3N=np.array(C)[o],
                    tau=tau if tau is not None else np.array([]))
print(f'{out}: {len(Qs)} Q values, shape {np.array(W).shape}')

"""
Final parametric forms of the dark-hadron MEs in BOTH q^2 and alpha_d,
WITH propagated uncertainties. Reads paper_final/final_forms.csv.

Master form (normalized matrix element = charge profile):
    <J_V0(q)> / <J_V0(0)> = [1 + q^2 b(alpha)^2 / (4p)]^(-p)
    meson:  p = 2 exactly
    baryon: p = pbar +- err (weighted mean over alpha; alpha-independent within errors)
    Coulomb: b(alpha) = c / alpha                  (c +- err)
    MRS:     b(alpha) = beta0 + beta1 x + beta2 x^2,  x = alpha - 0.3
             (coefficients with covariance propagated from the per-alpha b errors)

Outputs: paper_final/parametric_forms.tex  (appendix-ready)
         paper_final/parametric_forms.csv  (machine readable)
Also mirrors the .tex into the Overleaf project.
"""
import csv, os
import numpy as np

OUT = 'paper_final'
OVER = ("/Users/user/Library/CloudStorage/Dropbox/Apps/Overleaf/"
        "Dark baryons direct detection")

rows = list(csv.DictReader(open(f'{OUT}/final_forms.csv')))
get = lambda s, sy: sorted([r for r in rows if r['scheme'] == s and r['system'] == sy],
                           key=lambda r: float(r['alpha']))

def wmean(vals, errs):
    w = 1.0/np.array(errs)**2
    m = np.sum(w*np.array(vals))/np.sum(w)
    return m, 1.0/np.sqrt(np.sum(w))

def coul_fit(sub):
    """b = c/alpha, weighted LSQ, returns c, err, chi2/dof."""
    a = np.array([float(r['alpha']) for r in sub])
    b = np.array([float(r['b']) for r in sub]); e = np.array([float(r['b_err']) for r in sub])
    w = 1.0/e**2; X = 1.0/a
    c = np.sum(w*X*b)/np.sum(w*X*X); ce = 1.0/np.sqrt(np.sum(w*X*X))
    chi = np.sum(w*(c*X-b)**2)/max(len(a)-1, 1)
    return c, ce, chi

def quad_fit(sub, x0=0.3):
    """b(alpha)=beta0+beta1*x+beta2*x^2, x=alpha-x0. Exact 3-pt solve; coefficient
    covariance propagated from data errors: cov = (X^T W X)^{-1}."""
    a = np.array([float(r['alpha']) for r in sub])
    b = np.array([float(r['b']) for r in sub]); e = np.array([float(r['b_err']) for r in sub])
    x = a - x0
    X = np.vstack([np.ones_like(x), x, x*x]).T
    W = np.diag(1.0/e**2)
    cov = np.linalg.inv(X.T @ W @ X)
    beta = cov @ (X.T @ W @ b)
    return beta, np.sqrt(np.diag(cov))

lab = {'coul': 'Coulomb LO', 'mrs_lo': 'MRS LO', 'mrs_nlo': 'MRS NLO'}
out_rows = []
tex = ["% auto-generated by parametric_forms.py",
       "The complete parametric forms of the normalized charge matrix element,",
       "valid over $0.2\\le\\alpha_d\\le0.5$ and $q^2\\lesssim 0.25\\,m_\\psi^2$, are",
       "\\begin{equation}",
       "\\frac{\\langle J_{V^0}(q)\\rangle}{\\langle J_{V^0}(0)\\rangle}",
       "= \\Big[1+\\frac{q^2\\, b^2(\\alpha_d)}{4p}\\Big]^{-p},",
       "\\qquad x \\equiv \\alpha_d-0.3\\,,",
       "\\label{eq:app:paramform}",
       "\\end{equation}",
       "with, for each scheme and state ($1\\sigma$ uncertainties propagated from",
       "the per-coupling fits; meson $p=2$ fixed by the two-body bound state):",
       "\\begin{widetext}",
       "\\begin{align}"]

for sy in ['meson', 'baryon']:
    for s in ['coul', 'mrs_lo', 'mrs_nlo']:
        sub = get(s, sy)
        if len(sub) < 3: continue
        # p
        if sy == 'meson':
            pstr = "p=2"
            pv, pe = 2.0, 0.0
        else:
            pv, pe = wmean([float(r['p']) for r in sub], [max(float(r['p_err']), 1e-3) for r in sub])
            pstr = f"p={pv:.2f}({int(round(pe*100)):d})"
        # b(alpha)
        if s == 'coul':
            c, ce, chi = coul_fit(sub)
            bstr = f"b(\\alpha_d) = {c:.3f}({int(round(ce*1000))})/\\alpha_d"
            out_rows.append(dict(scheme=s, system=sy, form='b=c/alpha',
                                 c=c, c_err=ce, p=pv, p_err=pe, chi2=chi))
        else:
            beta, be = quad_fit(sub)
            bstr = (f"b(\\alpha_d) = {beta[0]:.3f}({int(round(be[0]*1000))})"
                    f" {beta[1]:+.2f}({int(round(be[1]*100))})\\,x"
                    f" {beta[2]:+.1f}({int(round(be[2]*10))})\\,x^2")
            out_rows.append(dict(scheme=s, system=sy, form='b=b0+b1*x+b2*x^2 (x=alpha-0.3)',
                                 b0=beta[0], b0_err=be[0], b1=beta[1], b1_err=be[1],
                                 b2=beta[2], b2_err=be[2], p=pv, p_err=pe))
        nm = f"\\text{{{lab[s]} {sy}}}"
        tex.append(f"{nm}:&\\quad {bstr}\\,,\\ \\ {pstr}\\,;\\\\")

tex[-1] = tex[-1].rstrip('\\\\') + ''
tex += ["\\end{align}",
        "\\end{widetext}",
        "The scalar splitting is fixed by the measured constituent kinetic energy,",
        "$F_S-F_1 = -(\\langle K\\rangle/2m_\\psi)\\,g(q^2)$ with $g(0)=1$ and the",
        "$\\langle K\\rangle$ values of Table~\\ref{tab:FF_fits}; the vector and",
        "tensor channels follow from the exact kinematic relations of",
        "Sec.~\\ref{app:gfmc:me2ff}. The Coulomb radius law",
        "$\\langle r^2\\rangle = \\tfrac32\\,c^2/\\alpha_d^2$ is exact; in the MRS",
        "schemes the quadratic renders the saturation",
        "$b(0.3)\\simeq b(0.5)$ explicit."]

with open(f'{OUT}/parametric_forms.tex', 'w') as f:
    f.write('\n'.join(tex) + '\n')

keys = sorted({k for r in out_rows for k in r})
with open(f'{OUT}/parametric_forms.csv', 'w', newline='') as f:
    w = csv.DictWriter(f, fieldnames=keys)
    w.writeheader()
    for r in out_rows: w.writerow(r)

if os.path.isdir(OVER):
    import shutil
    shutil.copy(f'{OUT}/parametric_forms.tex', os.path.join(OVER, 'parametric_forms.tex'))
    print("copied parametric_forms.tex into Overleaf")

for r in out_rows:
    print(" ", r)
